def custom_basis(kw: float) -> dict:
    """Interpolate the workbook ladder at a custom kW/rack. Outside 41-600 kW values are held flat
    at the end platform and flagged in_range=False. CSI mix and text fields come from the nearest
    platform."""
    names = CURVE_NAMES
    ks = [PLATFORMS[n]["kw"] for n in names]
    if kw <= ks[0]:
        lo = hi = names[0]; t = 0.0
    elif kw >= ks[-1]:
        lo = hi = names[-1]; t = 0.0
    else:
        j = max(i for i in range(len(ks) - 1) if ks[i] <= kw)
        lo, hi = names[j], names[j + 1]
        t = (kw - ks[j]) / (ks[j + 1] - ks[j])
    nearest = min(PLATFORMS, key=lambda n: abs(PLATFORMS[n]["kw"] - kw))
    out = dict(PLATFORMS[nearest])
    for f in NUMERIC:
        a, b = PLATFORMS[lo][f], PLATFORMS[hi][f]
        out[f] = a + (b - a) * t
    out["kw"] = kw
    out["in_range"] = ks[0] <= kw <= ks[-1]
    out["bracket"] = lo if lo == hi else f"{lo} - {hi}"
    out["nearest"] = nearest
    return out


def basis(platform: str, custom_kw: float | None = None) -> dict:
    if platform in PLATFORMS:
        b = dict(PLATFORMS[platform])
        b.update(in_range=True, bracket=platform, nearest=platform)
        return b
    return custom_basis(float(custom_kw or 135))


def band_check(value_per_mw: float, b: dict) -> str:
    if value_per_mw < b["low"] - 1:
        s = "BELOW BAND"
    elif value_per_mw > b["high"] + 1:
        s = "ABOVE BAND"
    else:
        s = "IN BAND"
    return s if b.get("in_range", True) else s + " (outside workbook density range)"


def quantities(it_mw: float, racks: float, pue: float, cdu_mw: float) -> dict:
    standby = it_mw * pue                                   # 25_REDUNDANCY r5, 01_ASSUME8 r34
    gens_n = math.ceil(round(standby / GEN_UNIT_MW, 9))     # 12_CHANGE_PRICING r16
    ups_n1 = math.ceil(round(UPS_FACTOR * it_mw / UPS_MODULE_MW, 9))  # r21: 110 on 100 MW
    cdus = (math.ceil(round(it_mw / cdu_mw, 9)) + 1) if cdu_mw else 0  # 20_CSI8_MATRIX D20
    return {"standby_mw": standby, "gens_n": gens_n, "gens_n1": gens_n + 1, "gens_n2": gens_n + 2,
            "gens_2n": 2 * gens_n, "ups_n1": ups_n1, "ups_2n": 2 * math.ceil(round(it_mw / UPS_MODULE_MW, 9)),
            "cdus": cdus, "taps": 2 * racks}
